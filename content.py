# ============================================================
#   ЗАНЯТЫЕ МЕСТА
# ============================================================
# Для каждой пары (фильм, сеанс, зал) заранее генерируется набор занятых мест
# так, чтобы зал был заполнен на 40-75%. Генерация детерминированная (по seed),
# чтобы занятость не менялась при каждом перезапуске бота.
#
# Для фильмов 18+ места (3, 6) и (3, 7) — то есть 3-й ряд, места 6 и 7 —
# всегда остаются свободными и никогда не попадают в число занятых.

ALWAYS_FREE_SEATS_FOR_18_PLUS = {(3, 6), (3, 7)}


def _generate_occupied_seats(movie: dict, session_idx: int, hall: str) -> set:
    """Генерирует детерминированный набор занятых мест для конкретного сеанса и зала."""
    seed = f"{movie['id']}-{session_idx}-{hall}"
    rng = random.Random(seed)

    all_seats = [(row, seat) for row in range(1, ROWS_COUNT + 1) for seat in range(1, SEATS_PER_ROW + 1)]
    total_seats = len(all_seats)

    is_18_plus = movie["age"] == "18+"
    if is_18_plus:
        candidates = [s for s in all_seats if s not in ALWAYS_FREE_SEATS_FOR_18_PLUS]
    else:
        candidates = list(all_seats)

    fill_ratio = rng.uniform(0.40, 0.75)
    occupied_count = min(round(total_seats * fill_ratio), len(candidates))

    return set(rng.sample(candidates, occupied_count))


# Предварительно рассчитываем занятость для всех связок фильм+сеанс+зал
_OCCUPIED_SEATS_CACHE = {}
for _movie in MOVIES:
    for _session_idx, _session in enumerate(_movie["sessions"]):
        for _hall in HALLS:
            _OCCUPIED_SEATS_CACHE[(_movie["id"], _session_idx, _hall)] = _generate_occupied_seats(
                _movie, _session_idx, _hall
            )


def get_occupied_seats(movie_id: int, session_idx: int, hall: str) -> set:
    """Вернуть множество занятых мест {(ряд, место), ...} для данного сеанса и зала."""
    return _OCCUPIED_SEATS_CACHE.get((movie_id, session_idx, hall), set())
